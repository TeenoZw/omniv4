    <div>
      <h2 class="text-lg font-semibold text-slate-900 dark:text-white">How to submit a request</h2>
      <p class="mt-2">
        Send your request to <a class="underline" href="mailto:info@omnilogistics.co.zw">info@omnilogistics.co.zw</a> with enough information for us to:
      </p>
      <ul class="mt-2 list-disc space-y-2 pl-5">
        <li>identify you and verify your authority to make the request;</li>
        <li>understand which records or personal information you are requesting;</li>
        <li>contact you about the request and any lawful requirements that apply; and</li>
        <li>respond within the applicable process and legal timeframes.</li>
      </ul>
    </div>

    <div>
      <h2 class="text-lg font-semibold text-slate-900 dark:text-white">Types of requests we can receive</h2>
      <ul class="mt-2 list-disc space-y-2 pl-5">
        <li>requests for access to records under PAIA;</li>
        <li>requests to access personal information held about you;</li>
        <li>requests to correct or update inaccurate personal information;</li>
        <li>requests to delete, destroy, or de-identify information where lawful;</li>
        <li>objections to certain processing activities; and</li>
        <li>privacy or security complaints relating to the use of personal information.</li>
      </ul>
    </div>

    <div>
      <h2 class="text-lg font-semibold text-slate-900 dark:text-white">Information we may ask for</h2>
      <ul class="mt-2 list-disc space-y-2 pl-5">
        <li>your full name and contact details;</li>
        <li>proof of identity or authority where needed;</li>
        <li>the exact record or information requested;</li>
        <li>the reason for the request where the law requires it; and</li>
        <li>any supporting context that helps us locate the correct records.</li>
      </ul>
    </div>

    <div>
      <h2 class="text-lg font-semibold text-slate-900 dark:text-white">Operational note</h2>
      <p class="mt-2">
        Where a prescribed Information Regulator form is required for a particular request type, Omni Logistics may ask the requester to
        complete that form or provide substantially similar information.
